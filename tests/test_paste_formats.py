@pytest.mark.parametrize(("paste", "expected"), [(paste, expected) for _title, paste, expected in CASES], ids=[case[0] for case in CASES])
def test_a_paste_reads_as_people_would_expect(paste, expected):
    rows = [row for row in plan_import(paste, [], CATALOG) if row.checked]
    assert [(row.name, tuple(row.tags), row.reason) for row in rows] == expected


def test_a_title_line_is_shown_but_not_checked():
    rows = plan_import("避雷名单（持续更新）\n小明 炸房", [], CATALOG)
    assert [(row.name, row.checked) for row in rows] == [("避雷名单", False), ("小明", True)]
